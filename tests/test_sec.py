def test_read_f13_corporate_read_institution_skipped_once_per_filing():
    big = F13_COVER.replace(b"<tableEntryTotal>6<", b"<tableEntryTotal>5432<")
    calls = []

    def fetch(u):
        calls.append(u)
        if u.endswith("primary_doc.xml"):
            return big if "/1364742/" in u else F13_COVER
        return F13_TABLE

    def fetch_json(u):
        calls.append(u)
        return {"directory": {"item": [{"name": "primary_doc.xml"}, {"name": "infotable.xml"}]}}
    old_out = fs.OUT
