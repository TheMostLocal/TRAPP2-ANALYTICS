def test_parse_13g_namespaced():
    r = fs.parse_sched13(G13)
    assert r["kind"] == "13G" and r["amendment"] is True
    assert r["issuerCik"] == 1769628 and r["issuerName"] == "CoreWeave, Inc." and r["cusip"] == "21873S108"
    assert r["event"] == "2026-09-30" and r["filerCik"] == 1045810 and r["cls"].startswith("Class A")
    assert len(r["persons"]) == 2
    nv = r["persons"][0]
    assert nv["name"] == "NVIDIA Corporation" and nv["pct"] == 6.6 and nv["shares"] == 24182460 and nv["type"] == "CO"
    assert r["persons"][1]["pct"] == 0.1 and r["persons"][1]["shares"] == 1000
    assert nv["cik"] is None and r["purpose"] is None                 # 13G: no per-person CIK, no purpose
    assert r["rule"] == "13d-1(d)" and r["issuerName"] == "CoreWeave, Inc."      # the rule; Item 1's repeat ignored


