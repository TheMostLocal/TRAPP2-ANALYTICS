def test_filed_by_it_from_file_numbers_and_agents():
    """BlackRock files through agents (accession prefix not its CIK) - its schedules about OTHER companies still show in
    their file numbers: each 005- number belongs to a subject; the one most of its list shares is BlackRock's own."""
    def sub(rows):
        return {"filings": {"recent": {"form": [r[0] for r in rows], "filingDate": [r[1] for r in rows], "accessionNumber": [r[2] for r in rows],
                                       "primaryDocument": ["primary_doc.xml"] * len(rows), "fileNumber": [r[3] for r in rows]}}}
    about = [("SCHEDULE 13G/A", "2026-02-01", f"0000102909-26-{i:06d}", "005-81187") for i in range(3)]          # Vanguard etc. on BLK
    mine = [("SCHEDULE 13G", "2026-03-01", f"0000950103-26-{i:06d}", f"005-9{i:04d}") for i in range(fs.SCHED13_MASS + 3)]   # agent-filed, on others
    other = [("10-K", "2026-02-20", "0001364742-26-000009", "001-33099")]
    s1 = sub(about + mine + other)
    by = fs.filed_by_it(s1, 1364742)
    assert by == {r[2] for r in mine}
    q, mass = fs.queue13(s1, TODAY, 1364742, {})
    assert mass is True and sorted(x[1] for x in q) == sorted(r[2] for r in about)
    # a company with one schedule about it: no file-number majority - only the accession prefix tells
    s2 = sub([("SCHEDULE 13G", "2026-03-01", "0001045810-26-000001", "005-94943"), ("SCHEDULE 13G", "2026-04-01", "0000921895-26-000002", "005-11111")])
    assert fs.filed_by_it(s2, 1045810) == {"0001045810-26-000001"}
    assert fs.filed_by_it({}, 1) == set()


