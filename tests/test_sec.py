def test_read_sched13_budget_priority_dedupe_and_seen():
    calls = []

    def fake(url):
        calls.append(url)
        if "bad" in url:
            raise ValueError("boom")
        return by_url(url)

    old_out = fs.OUT
    with tempfile.TemporaryDirectory() as d:
        fs.OUT = Path(d)
        try:
            docs = {"GOOG": {"ticker": "GOOG"}, "GOOGL": {"ticker": "GOOGL"}, "AAA": {"ticker": "AAA"}, "ZZZ": {"ticker": "ZZZ"}}
            cik = {"GOOG": 1652044, "GOOGL": 1652044, "AAA": 1, "ZZZ": 2}
            pend = {"GOOG": [("2026-10-01", "g-1", "x/primary_doc.xml", "SCHEDULE 13G")],
                    "GOOGL": [("2026-10-01", "g-1", "x/primary_doc.xml", "SCHEDULE 13G")],          # the same filing
                    "AAA": [("2026-11-01", "a-13d", "x/primary_doc.xml", "SCHEDULE 13D"),
                            ("2026-09-01", "a-bad", "x/primary_doc.xml", "SCHEDULE 13G")],
                    "ZZZ": [("2026-11-15", "z-1", "x/primary_doc.xml", "SCHEDULE 13G/A")]}
            # budget 3, GOOGL a web name: GOOGL's filing first (shared with GOOG - read once), then the newest (ZZZ, AAA 13D)
            n = fs.read_sched13(pend, docs, cik, TODAY, {"GOOGL"}, 3, fetch=lambda u: fake(u.replace("a-13d", "13d")))
            assert n == 3 and len(calls) == 3
            assert calls[0].endswith("/1652044/g1/primary_doc.xml")
            assert docs["GOOG"]["holders"][0]["name"] == "NVIDIA Corporation" and docs["GOOGL"]["holders"] == docs["GOOG"]["holders"]
            assert docs["AAA"]["holders"][0]["kind"] == "13D" and "a-bad" not in docs["AAA"]["s13Seen"]       # over budget: still pending
            assert docs["ZZZ"]["holders"][0]["pct"] == 6.6 and json.loads(Path(d, "ZZZ.json").read_text())["holders"]
            # next run: the unreadable one is read, fails, and is marked seen - never retried
            n2 = fs.read_sched13({"AAA": [("2026-09-01", "a-bad", "x/primary_doc.xml", "SCHEDULE 13G")]}, docs, cik, TODAY, set(), 5, fetch=fake)
            assert n2 == 1 and "a-bad" in docs["AAA"]["s13Seen"] and len(docs["AAA"]["s13"]) == 1
        finally:
            fs.OUT = old_out


def test_read_sched13_breadth_first_and_the_queue_drains_across_runs():
    old_out = fs.OUT
    with tempfile.TemporaryDirectory() as d:
        fs.OUT = Path(d)
        try:
            a_rows = [["2026-11-10", "a3", "primary_doc.xml", "SCHEDULE 13G/A"], ["2026-11-09", "a2", "primary_doc.xml", "SCHEDULE 13G"],
                      ["2026-11-08", "a1", "primary_doc.xml", "SCHEDULE 13G"]]
            docs = {"A": {"ticker": "A", "s13Pend": [list(x) for x in a_rows]},
                    "B": {"ticker": "B", "s13Pend": [["2026-10-01", "b1", "primary_doc.xml", "SCHEDULE 13G"]]}}
            read = []
            fetch = lambda u: (read.append(u.split("/")[-2]), G13)[1]
            pend = {t: [tuple(x) for x in v["s13Pend"]] for t, v in docs.items()}
            assert fs.read_sched13(pend, docs, {"A": 1, "B": 2}, TODAY, set(), 2, fetch=fetch) == 2
            assert read == ["a3", "b1"]                                  # each company's newest before anyone's second
            assert [x[1] for x in docs["A"]["s13Pend"]] == ["a2", "a1"] and docs["B"]["s13Pend"] == []
            pend = {t: [tuple(x) for x in v["s13Pend"]] for t, v in docs.items() if v.get("s13Pend")}
            assert fs.read_sched13(pend, docs, {"A": 1, "B": 2}, TODAY, set(), 5, fetch=fetch) == 2      # the next run
            assert read == ["a3", "b1", "a2", "a1"] and docs["A"]["s13Pend"] == [] and len(docs["A"]["s13Seen"]) == 3
        finally:
            fs.OUT = old_out


