def about(xml, cik):
    """The sample filed about another issuer (its issuer CIK swapped)."""
    return xml.replace(b"<issuerCik>0001769628</issuerCik>", f"<issuerCik>{cik:010d}</issuerCik>".encode()) \
              .replace(b"<issuerCIK>0000012345</issuerCIK>", f"<issuerCIK>{cik:010d}</issuerCIK>".encode())


def by_url(url, xml=None):
    """A fake SEC: the document at /data/<cik>/... is about that cik."""
    c = int(url.split("/data/")[1].split("/")[0])
    return about(xml if xml is not None else (D13 if "13d" in url else G13), c)


def R(name, filed, pct, **kw):
    return dict({"kind": "13G", "amend": False, "event": filed, "filed": filed, "acc": f"acc-{name}-{filed}", "filerCik": None,
                 "name": name, "cik": None, "pct": pct, "shares": None, "type": "IA", "n": 1, "cusip": "C1"}, **kw)


